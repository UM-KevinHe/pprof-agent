"""The run: profile -> specification -> complete -> verify -> admissible -> loop -> report -> repro.

`run_analysis` is the whole agent without a model: the CLI, the tests and the no-model deployment call
it. A model, when configured, replaces `parse_reply` by prose extraction and `default_planner` by the
planner act; nothing between changes.
"""
from __future__ import annotations

import hashlib
import json
import os
import platform
import sys
import time
from pathlib import Path
from typing import Any, Callable, Dict, Optional

from . import __version__, loop, report, rules, specification as S
from .engine import executor
from .engine.rbridge import RError
from .state import Session


def new_run_dir(base: str, name: Optional[str] = None) -> Path:
    stamp = time.strftime("%Y%m%d_%H%M%S")
    run = Path(base) / (name or f"run_{stamp}")
    for sub in ("payloads", "outputs", "tables", "figures"):
        (run / sub).mkdir(parents=True, exist_ok=True)
    return run


def fingerprint(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def config_hash(spec: S.MeasureSpecification, data_path: str, extra: Optional[Dict[str, Any]] = None) -> str:
    """The configuration that executes, hashed: the specification's fields, the data's bytes, the
    engine's settings and the thresholds the rules used."""
    payload = {"spec": spec.config(), "data_sha256": fingerprint(data_path),
               "tol": executor.DEFAULT_TOL, "bound": executor.DEFAULT_BOUND, "seed": executor.DEFAULT_SEED,
               "thresholds": rules.THRESHOLDS, "version": __version__}
    if extra:
        payload.update(extra)
    return hashlib.sha256(json.dumps(payload, sort_keys=True, default=str).encode()).hexdigest()


def write_repro(session: Session) -> Path:
    """An R script that replays every engine step from the recorded payloads, with no model."""
    run = Path(session.run_dir)
    scripts_dir = Path(os.environ.get("PPROF_AGENT_R_SCRIPTS", str(Path(__file__).resolve().parent.parent / "r_scripts")))
    lines = ["#!/usr/bin/env Rscript",
             "# repro.R -- replays the analysis from its recorded payloads; no language model is involved.",
             f"# run directory: {run}", f"# configuration hash: {session.config_hash}",
             f"# generated by pprof_agent {__version__} on {time.strftime('%Y-%m-%d %H:%M')}",
             "args <- commandArgs(trailingOnly = TRUE)",
             f"scripts <- if (length(args)) args[1] else {json.dumps(str(scripts_dir))}",
             f"out <- if (length(args) > 1) args[2] else file.path({json.dumps(str(run))}, 'replay')",
             "dir.create(file.path(out, 'tables'), showWarnings = FALSE, recursive = TRUE)",
             "dir.create(file.path(out, 'outputs'), showWarnings = FALSE, recursive = TRUE)",
             "replay <- function(script, payload_file, label) {",
             "  p <- jsonlite::fromJSON(payload_file, simplifyVector = FALSE)",
             "  if (!is.null(p$run_dir)) p$run_dir <- out",
             "  pf <- file.path(out, paste0(label, '.payload.json'))",
             "  jsonlite::write_json(p, pf, auto_unbox = TRUE, digits = NA, null = 'null', na = 'null')",
             "  status <- system2('Rscript', c('--no-save', '--no-restore', '--no-init-file', file.path(scripts, script), pf, file.path(out, 'outputs', paste0(label, '.json'))))",
             "  cat(sprintf('%-40s exit %d\\n', label, status))",
             "  if (status != 0) stop('replay failed at ', label)",
             "}"]
    for p in sorted((run / "payloads").glob("*.json")):
        label = p.stem
        action = _action_of(label)
        if action in executor.SCRIPTS:
            lines.append(f"replay({json.dumps(executor.SCRIPTS[action])}, {json.dumps(str(p))}, {json.dumps(label)})")
    lines.append("cat('replayed; compare out/tables with the original tables\\n')")
    p = run / "repro.R"
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return p


# payload labels are `<step>_<result id with ':' as '_'>`; the result id's prefix names the action
_LABEL_ACTIONS = (("profile", "profile"), ("verify", "verify"), ("fit", "fit"), ("sm", "standardize"),
                  ("measure", "test_measure"), ("test", "test_providers"), ("en", "empirical_null"),
                  ("selection", "select_adjusters"), ("evaluation", "evaluate_model"),
                  ("calibration", "calibrate_tests"), ("subset", "subset"))


def _action_of(label: str) -> str:
    rest = label.split("_", 1)[1] if "_" in label else label
    for prefix, action in _LABEL_ACTIONS:
        if rest == prefix or rest.startswith(prefix + "_"):
            return action
    return rest


def write_artifacts(session: Session, prose: Optional[Dict[str, str]] = None) -> Dict[str, str]:
    run = Path(session.run_dir)
    (run / "spec.json").write_text(session.spec.to_json(), encoding="utf-8")
    (run / "card.json").write_text(json.dumps(session.card, indent=1), encoding="utf-8")
    if prose is not None:
        session.prose = dict(prose)
    md = report.render_markdown(session, prose=session.prose or None)
    (run / "report.md").write_text(md, encoding="utf-8")
    out = {"report": str(run / "report.md"), "spec": str(run / "spec.json"), "trace": str(run / "trace.json")}
    try:
        from . import htmlreport
        out["html"] = str(htmlreport.write(md, run, title=f"Provider profiling: {session.spec.outcome} per {session.spec.unit}"))
    except Exception as exc:  # noqa: BLE001
        session.refusals.append(f"html report not rendered: {exc}")
    out["repro"] = str(write_repro(session))
    session.save("trace.json")
    return out


def run_analysis(data_path: str, out_dir: str, spec_dict: Optional[Dict[str, Any]] = None,
                 reply: Optional[str] = None, planner: Optional[Callable] = None, budget: int = 30,
                 name: Optional[str] = None, log: Callable[[str], None] = print,
                 figures: bool = True, extras: Optional[list] = None) -> Session:
    """The whole run without a model. Returns the session; `session.phase` says where it stopped
    (DECLARING: the question is in `session.question`; REFUSED: `session.verification.refusals`)."""
    run = new_run_dir(out_dir, name)
    session = Session(data_path=str(data_path), run_dir=str(run), budget=budget)
    log(f"run directory: {run}")
    executor.profile(session)
    spec = S.MeasureSpecification.from_dict(spec_dict or {}, source="quoted")
    spec, items = S.complete(spec, session.profile)
    if items and reply:
        spec, problems = S.parse_reply(reply, spec, session.profile)
        if problems:
            log("reply problems: " + "; ".join(problems))
        spec, items = S.complete(spec, session.profile)
    session.spec, session.open_items = spec, items
    if items:
        session.question = S.render_question(items)
        log(session.question)
        session.save("trace.json")
        return session
    try:
        card = executor.verify_card(session)
    except RError as exc:
        session.verification = S.Verification(False, [f"verification failed in the engine: {exc.info.get('message')}"], [], {})
        session.save("trace.json")
        return session
    session.verification = S.verify(spec, card)
    if not session.verification.ok:
        log("refused: " + "; ".join(session.verification.refusals))
        session.save("trace.json")
        return session
    session.admissible = rules.admissible(card, spec)
    session.config_hash = config_hash(spec, data_path)
    log(f"admissible: {session.admissible.tests_computed}; reported: {session.admissible.tests_reported}; "
        f"default {session.admissible.default_test}; references {session.admissible.references_computed}")
    loop.run_loop(session, planner=planner, log=log)
    for name_, args_ in (extras or []):      # harness-triggered extras (the CLI's --calibrate / --subset)
        probs = __import__("pprof_agent.actions", fromlist=["validate"]).validate(name_, args_, session)
        if probs:
            session.refusals.append(f"{name_}: " + "; ".join(probs))
            log(f"{name_} refused: {'; '.join(probs)}")
            continue
        try:
            res = executor.execute(session, name_, args_, source="harness", reason="requested on the command line")
            log(f"extra {res.step}: {res.id} ({res.seconds}s)")
        except RError as exc:
            session.refusals.append(f"{name_} failed in the engine: {exc.info.get('message', '')}")
            log(f"extra {name_} failed: {exc.info.get('message', '')}")
    if extras:
        loop.recommend(session)
        for axis in ("statistic", "variance", "reference", "standardization"):
            executor.execute(session, "compare_axes", {"axis": axis}, source="harness", reason="flags under alternatives")
    if figures:
        try:
            from .engine import pycore
            pycore.default_figures(session, log=log)
        except Exception as exc:  # noqa: BLE001
            session.refusals.append(f"figures not rendered: {exc}")
            log(f"figures not rendered: {exc}")
    paths = write_artifacts(session)
    log(f"report: {paths['report']}")
    return session


def environment() -> Dict[str, Any]:
    return {"python": sys.version.split()[0], "platform": platform.platform(), "pprof_agent": __version__,
            "slurm_job": os.environ.get("SLURM_JOB_ID"), "cpus": os.environ.get("SLURM_CPUS_PER_TASK")}
